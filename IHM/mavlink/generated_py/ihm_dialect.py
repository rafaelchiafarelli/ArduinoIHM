    def pwm_channel_config_encode(self, channel: int, f_selector: int, frequency: int, out1_enabled: int, out1_inverting: int, out1_duty_percent: int, out2_enabled: int, out2_inverting: int, out2_duty_percent: int, out3_enabled: int, out3_inverting: int, out3_duty_percent: int) -> MAVLink_pwm_channel_config_message:
        """
        Configure one of the board's 4 PWM channels. PC -> board, command.
        The board applies it to the timer registers immediately; there
        is         no ack. Sending a new config for a channel replaces
        its previous         one (last writer wins, including against
        the on-screen PWM tab,         which drives the same
        registers).          One message shape covers both channel
        kinds (see         IHM/lib/MultiOutput/src/PWM.h):           *
        channels 0 and 1 are "simplex" -- a single output (OC3A /
        OC5A). Only out1_* is used; out2_* and out3_* are ignored.
        * channels 2 and 3 are "complex" -- three independent outputs
        A/B/C (OC1A/B/C, OC4A/B/C). out1_/out2_/out3_ map to A/B/C.
        Same "not bit-packed across byte boundaries" convention as the
        other messages here -- each flag gets its own byte. 13 bytes,
        well under the 64-byte cap.

        channel                   : Target PWM channel, 0-3. Out-of-range configs are dropped by the board. (type:uint8_t)
        f_selector                : Frequency selector for the whole channel. (type:uint8_t, values:PWM_FREQUENCY)
        frequency                 : Raw ICRn TOP (timer period). Only read when f_selector ==
        PWM_FREQUENCY_VARIABLE; ignored for every fixed selector. (type:uint16_t)
        out1_enabled              : Output A: 1 = drive the pin, 0 = disconnect it. (type:uint8_t)
        out1_inverting            : Output A: 0 = non-inverting (high from period start), 1 = inverting. (type:uint8_t)
        out1_duty_percent         : Output A duty cycle, 0-100. Scaled against the selector's resolution on-board. (type:uint8_t)
        out2_enabled              : Output B enable. Ignored for channels 0 and 1. (type:uint8_t)
        out2_inverting            : Output B edge polarity. Ignored for channels 0 and 1. (type:uint8_t)
        out2_duty_percent         : Output B duty cycle, 0-100. Ignored for channels 0 and 1. (type:uint8_t)
        out3_enabled              : Output C enable. Ignored for channels 0 and 1. (type:uint8_t)
        out3_inverting            : Output C edge polarity. Ignored for channels 0 and 1. (type:uint8_t)
        out3_duty_percent         : Output C duty cycle, 0-100. Ignored for channels 0 and 1. (type:uint8_t)

        """
        return MAVLink_pwm_channel_config_message(channel, f_selector, frequency, out1_enabled, out1_inverting, out1_duty_percent, out2_enabled, out2_inverting, out2_duty_percent, out3_enabled, out3_inverting, out3_duty_percent)

